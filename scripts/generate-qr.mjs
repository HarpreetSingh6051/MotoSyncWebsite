import fs from 'node:fs'
import path from 'node:path'
import QRCode from 'qrcode'

const url = process.env.VITE_RIDER_URL || 'https://moto-sync.vercel.app'

const qr = QRCode.create(url, { errorCorrectionLevel: 'M' })
const size = qr.modules.size
const data = qr.modules.data
const quiet = 4

const rows = []
for (let y = 0; y < size; y += 1) {
  const row = []
  for (let x = 0; x < size; x += 1) {
    row.push(data[y * size + x] ? 1 : 0)
  }
  rows.push(row)
}

const output = `// Generated by scripts/generate-qr.mjs. Do not edit by hand.
// Encodes: ${url}
export const QR_SIZE = ${size}
export const QR_QUIET_ZONE = ${quiet}
export const QR_MATRIX: number[][] = ${JSON.stringify(rows)}
`

const target = path.resolve(process.cwd(), 'src/lib/qr-matrix.ts')
fs.mkdirSync(path.dirname(target), { recursive: true })
fs.writeFileSync(target, output, 'utf8')
console.log(`Generated ${size}x${size} QR matrix for ${url}`)
